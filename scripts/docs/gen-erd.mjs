#!/usr/bin/env node
// Generates the ERD (Mermaid) + table inventory section of docs/DATABASE.md straight from packages/database/prisma/schema.prisma,
// so the diagram can never drift from the schema.   node scripts/docs/gen-erd.mjs            (rewrites the generated block)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const schema = readFileSync(resolve(root, 'packages/database/prisma/schema.prisma'), 'utf8');
const enums = new Set([...schema.matchAll(/^enum (\w+) \{/gm)].map((m) => m[1]));
const models = [];
for (const m of schema.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)) {
  const fields = [];
  let table = m[1];
  for (const line of m[2].split('\n')) {
    const t = line.trim();
    const map = /^@@map\("([^"]+)"\)/.exec(t);
    if (map) table = map[1];
    const f = /^(\w+)\s+([\w]+)(\[\])?(\?)?\s*(.*)$/.exec(t);
    if (!f || t.startsWith('@@') || t.startsWith('//')) continue;
    fields.push({ name: f[1], type: f[2], list: !!f[3], optional: !!f[4], attrs: f[5].split('//')[0] });
  }
  models.push({ name: m[1], table, fields });
}
const names = new Set(models.map((m) => m.name));
const rels = [];
for (const m of models)
  for (const f of m.fields) {
    if (!names.has(f.type) || !/@relation\(.*fields:/.test(f.attrs)) continue; // owning side only
    rels.push({ from: m.name, to: f.type, optional: f.optional, label: f.name });
  }
const scalar = (f) => (enums.has(f.type) ? 'enum' : f.type.toLowerCase());
let md = '```mermaid\nerDiagram\n';
for (const r of rels) md += `  ${r.to} ${r.optional ? '|o' : '||'}--o{ ${r.from} : "${r.label}"\n`;
for (const m of models) {
  md += `  ${m.name} {\n`;
  for (const f of m.fields) {
    if (names.has(f.type)) continue;
    const key = /@id\b/.test(f.attrs) ? ' PK' : /@unique/.test(f.attrs) ? ' UK' : '';
    md += `    ${scalar(f)}${f.list ? '_array' : ''} ${f.name}${key}\n`;
  }
  md += '  }\n';
}
md += '```\n';
let inv = `| Model | Table | Columns | Foreign keys |\n|---|---|---:|---:|\n`;
for (const m of models) inv += `| ${m.name} | \`${m.table}\` | ${m.fields.filter((f) => !names.has(f.type)).length} | ${rels.filter((r) => r.from === m.name).length} |\n`;
const block = `<!-- ERD:BEGIN (generated by scripts/docs/gen-erd.mjs — do not edit by hand) -->\n\n${models.length} models, ${rels.length} foreign-key relations, ${enums.size} enums.\n\n${md}\n${inv}\n<!-- ERD:END -->`;
const file = resolve(root, 'docs/DATABASE.md');
const cur = existsSync(file) ? readFileSync(file, 'utf8') : '';
const next = /<!-- ERD:BEGIN[\s\S]*<!-- ERD:END -->/.test(cur) ? cur.replace(/<!-- ERD:BEGIN[\s\S]*<!-- ERD:END -->/, () => block) : `${cur}\n${block}\n`;
writeFileSync(file, next);
console.log(`ERD written: ${models.length} models, ${rels.length} relations`);
